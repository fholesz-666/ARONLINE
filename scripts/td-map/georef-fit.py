px=np.array(px); ll=np.array(ll)
def feats(lon,lat,deg):
    a=lon-15.5; b=lat-49.8
    f=[np.ones_like(a),a,b]
    if deg>=2: f+= [a*a,a*b,b*b]
    return np.stack(f,-1)
for deg in (1,2):
    F=feats(ll[:,0],ll[:,1],deg)
    cx,*_=np.linalg.lstsq(F,px[:,0],rcond=None); cy,*_=np.linalg.lstsq(F,px[:,1],rcond=None)
    res=np.hypot(F@cx-px[:,0],F@cy-px[:,1])
    print(deg,res.max().round(2),res.mean().round(2))
    print(list(cx.round(5)),list(cy.round(5)))
